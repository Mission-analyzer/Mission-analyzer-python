-- wipe-passed-waypoints.lua -- навчальна демонстрація: затирання
-- вмісту пункту маршруту ОДРАЗУ ПІСЛЯ того, як апарат перейшов на
-- наступний (координати/параметри пройденого пункту замінюються на
-- нульові -- оригінальні дані більше не відновити з самої місії).
--
-- === НАВІЩО ТАК, А НЕ ІНАКШЕ ===
-- 1. mission:set_item() -- ЄДИНИЙ офіційний спосіб змінити вміст
--    пункту місії з Lua (mission:clear() видаляє ВСЮ місію одразу,
--    "видалити один пункт зі зсувом решти" в API взагалі немає --
--    AP_Mission зберігає місію як масив ФІКСОВАНОЇ довжини).
-- 2. Викликається РІВНО ОДИН РАЗ на кожен перехід між пунктами (не в
--    циклі!) -- задокументований баг ArduPilot (issue #15997): часті
--    виклики mission:set_item() підряд (напр. у циклі на кожен tick)
--    переповнюють чергу збереження параметрів і МОЖУТЬ ПІДВІСИТИ
--    контролер у реальному польоті. Перехід між пунктами трапляється
--    природно рідко (секунди-хвилини між ними), тому це безпечно.
-- 3. Лог-файл (APM/LOGS/*.bin) НЕ чіпається напряму -- він активно
--    дозаписується самою прошивкою просто зараз, це ризиковано (може
--    пошкодити активний файл чи підвісити систему, і немає
--    підтвердженої документації, що файловий доступ Lua-скриптів
--    взагалі сягає за межі власної теки scripts/). Замість цього --
--    logger:write() -- офіційний, документований спосіб додати
--    власний запис У ВЖЕ ІСНУЮЧИЙ потік логування (той самий
--    механізм, що й у прикладі ArduPilot examples/logging.lua) --
--    "могильний камінь" з номером пункту й часом стирання, БЕЗ
--    прямого доступу до файлової системи.
--
-- Реальне видалення файлів логів (якщо потрібно саме це, а не
-- "могильний камінь" усередині логу) -- окрема, ПІСЛЯПОЛЬОТНА
-- операція через MAVFTP з боку наземної станції (Mission Analyzer),
-- не з цього скрипта в польоті.

local UPDATE_PERIOD_MS = 500  -- перевірка зміни поточного пункту -- не потрібно частіше, перехід між WP природно рідкісний

local last_seen_index = -1

function update()
    local current_index = mission:get_current_nav_index()

    if current_index and current_index ~= last_seen_index then
        -- перший виклик (last_seen_index == -1) -- просто запам'ятовуємо
        -- стартовий пункт, ще нема що затирати (місія щойно почалась)
        if last_seen_index >= 0 and current_index > last_seen_index then
            local passed_index = last_seen_index

            -- mission:get_item()/set_item() працюють з mavlink_mission_
            -- item_int_t -- те саме, що приходить/іде по MAVLink
            local old_item = mission:get_item(passed_index)
            if old_item then
                -- зберігаємо command/frame (структура пункту лишається
                -- валідною -- звичайний NAV_WAYPOINT), АЛЕ координати й
                -- усі параметри -- нульові: оригінальні дані про ЦЮ
                -- конкретну точку в реальному світі більше не відновити
                -- з самої місії.
                old_item:x(0)
                old_item:y(0)
                old_item:z(0)
                old_item:param1(0)
                old_item:param2(0)
                old_item:param3(0)
                old_item:param4(0)

                local ok = mission:set_item(passed_index, old_item)
                if ok then
                    gcs:send_text(0, string.format(
                        "wipe: пункт %d затерто (перехід на %d)", passed_index, current_index))
                    -- "могильний камінь" у лозі -- офіційний logger:write(),
                    -- НЕ прямий доступ до файлової системи. Формат "I" --
                    -- ціле число (номер затертого пункту), timestamp Lua
                    -- додає сам автоматично.
                    logger:write("WIPE", "wp_index", "I", passed_index)
                else
                    gcs:send_text(0, string.format(
                        "wipe: НЕ вдалось затерти пункт %d", passed_index))
                end
            end
        end

        last_seen_index = current_index
    end

    return update, UPDATE_PERIOD_MS
end

return update()
